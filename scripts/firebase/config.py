#!/usr/bin/env python3
"""Read-only Firebase discovery and validated local SDK configuration."""
import argparse
import json
import os
from pathlib import Path
import plistlib
import re
import shutil
import subprocess
import sys
import tempfile
import urllib.request

ROOT = Path(__file__).resolve().parents[2]


class ConfigError(Exception):
    pass


def paths(root, env):
    return (root / f"mobile_app/ios/{env}/GoogleService-Info.plist",
            root / f"mobile_app/ios/Flutter/Firebase-{env}.xcconfig")


def identity(root, env):
    project = f"everyone-teigi-{env}"
    identifier = 'com.toda.teigiii' + ('.dev' if env == 'dev' else '')
    return project, identifier


def client_id(value):
    if not isinstance(value, str) or not re.fullmatch(r'[A-Za-z0-9.-]+\.apps\.googleusercontent\.com', value):
        raise ConfigError("Missing or invalid OAuth client ID; enable Google provider and download SDK config again")
    return value


def validate(ios_data, project, bundle, app_id=None):
    ios = plistlib.loads(ios_data)
    if ios.get('PROJECT_ID') != project or ios.get('BUNDLE_ID') != bundle:
        raise ConfigError("iOS project/bundle mismatch")
    if not all(ios.get(k) for k in ['GOOGLE_APP_ID', 'API_KEY', 'GCM_SENDER_ID']):
        raise ConfigError("Incomplete iOS SDK configuration")
    if app_id and ios.get('GOOGLE_APP_ID') != app_id:
        raise ConfigError("SDK app ID does not match discovered app")
    ios_id = client_id(ios.get('CLIENT_ID'))
    reversed_id = '.'.join(reversed(ios_id.split('.')))
    if ios.get('REVERSED_CLIENT_ID') != reversed_id:
        raise ConfigError("Missing or inconsistent REVERSED_CLIENT_ID")
    return f"// Generated by just firebase-configure; do not edit.\nGOOGLE_IOS_CLIENT_ID={ios_id}\nGOOGLE_IOS_REVERSED_CLIENT_ID={reversed_id}\n".encode()


def validate_dart_options(root, env, ios_data):
    options = root / f'mobile_app/lib/util/firebase_options/firebase_options_{env}.dart'
    source = options.read_text()
    sections = re.findall(r'static const FirebaseOptions ios = FirebaseOptions\((.*?)\n  \);', source, re.S)
    if len(sections) != 1:
        raise ConfigError("Cannot identify iOS FirebaseOptions; local configuration was not changed")
    ios = plistlib.loads(ios_data)
    for dart_key, plist_key in [('appId', 'GOOGLE_APP_ID'), ('projectId', 'PROJECT_ID'), ('iosBundleId', 'BUNDLE_ID')]:
        values = re.findall(r"^\s*" + dart_key + r": '([^']*)',", sections[0], re.M)
        if values != [ios[plist_key]]:
            raise ConfigError(f"iOS FirebaseOptions {dart_key} mismatch; reconcile Dart options before configuring")


def firebase(*args):
    result = subprocess.run(['firebase', *args, '--json', '--non-interactive'], capture_output=True, check=False, timeout=60)
    if result.returncode:
        raise ConfigError("Firebase CLI failed; run firebase login and verify project permissions (CLI output suppressed)")
    try:
        body = json.loads(result.stdout)
        if body.get('status') != 'success':
            raise ValueError()
        return body['result']
    except (ValueError, KeyError, TypeError):
        raise ConfigError("Invalid Firebase CLI response") from None


def select_app(apps, identifier, project):
    matches = [a for a in apps if a.get('platform') == 'IOS' and a.get('bundleId') == identifier]
    if len(matches) != 1:
        raise ConfigError(f"Expected exactly one IOS app matching {identifier}; found {len(matches)}")
    app = matches[0]
    number = {'everyone-teigi-dev': '225028441501', 'everyone-teigi-prod': '713374936833'}[project]
    if app.get('projectId') != project and not any(app.get('name', '').startswith(f'projects/{p}/') for p in [project, number]):
        raise ConfigError("Discovered app project mismatch")
    return app['appId']


def replace_configs(updates):
    staged, backups, replaced = {}, {}, []
    retained_backups = set()
    try:
        for path, data in updates:
            if path.exists() and path.read_bytes() == data:
                continue
            path.parent.mkdir(parents=True, exist_ok=True)
            with tempfile.NamedTemporaryFile(dir=path.parent, delete=False) as out:
                staged[path] = Path(out.name)
                out.write(data)
        for path in staged:
            backups[path] = None
            if path.exists():
                with tempfile.NamedTemporaryFile(dir=path.parent, delete=False) as out:
                    backups[path] = Path(out.name)
                shutil.copy2(path, backups[path])
        for path, temporary in staged.items():
            os.replace(temporary, path)
            replaced.append(path)
    except Exception:
        failed = False
        for path in reversed(replaced):
            try:
                if backups[path] is None:
                    path.unlink(missing_ok=True)
                else:
                    os.replace(backups[path], path)
            except OSError:
                failed = True
                if backups[path] is not None:
                    retained_backups.add(backups[path])
        if failed:
            raise ConfigError("Configuration update failed and rollback was incomplete; verify local configuration") from None
        raise
    finally:
        for temporary in [*staged.values(), *backups.values()]:
            if temporary is not None and temporary not in retained_backups:
                try:
                    temporary.unlink(missing_ok=True)
                except OSError:
                    pass


def configure(root, env):
    project, bundle = identity(root, env)
    app_id = select_app(firebase('apps:list', 'IOS', '--project', project), bundle, project)
    data = firebase('apps:sdkconfig', 'IOS', app_id, '--project', project)['fileContents'].encode()
    generated = validate(data, project, bundle, app_id)
    validate_dart_options(root, env, data)
    # All remote data is validated before any destination is touched.
    replace_configs(list(zip(paths(root, env), [data, generated])))


def check(root, env):
    project, bundle = identity(root, env)
    ios, generated = paths(root, env)
    expected = validate(ios.read_bytes(), project, bundle)
    validate_dart_options(root, env, ios.read_bytes())
    if not generated.exists() or generated.read_bytes() != expected:
        raise ConfigError(f"OAuth xcconfig missing/stale; run just firebase-configure {env}")


def audit(env):
    # ADC is intentionally separate from firebase login. Never print credentials or provider secrets.
    result = subprocess.run(['gcloud', 'auth', 'application-default', 'print-access-token'], capture_output=True)
    if result.returncode:
        raise ConfigError("Provider audit requires gcloud ADC (gcloud auth application-default login); firebase login alone is insufficient")
    project = f'everyone-teigi-{env}'
    request = urllib.request.Request(f'https://identitytoolkit.googleapis.com/admin/v2/projects/{project}/defaultSupportedIdpConfigs', headers={'Authorization': 'Bearer ' + result.stdout.decode().strip(), 'x-goog-user-project': project})
    with urllib.request.urlopen(request, timeout=30) as response:
        configs = json.load(response).get('defaultSupportedIdpConfigs', [])
    for provider in ['apple.com', 'google.com']:
        matched = [c for c in configs if c.get('name', '').endswith('/' + provider)]
        print(f"{provider}: " + ('enabled' if matched and matched[0].get('enabled') else 'disabled or absent'))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=['configure', 'check', 'audit'])
    parser.add_argument('env', choices=['dev', 'prod'])
    args = parser.parse_args()
    try:
        if args.command == 'audit':
            audit(args.env)
        else:
            globals()[args.command](ROOT, args.env)
        print(f"Firebase {args.env} {args.command}: " + ('complete' if args.command == 'audit' else 'OK'))
    except Exception as error:
        # Parse failures and HTTP/CLI errors must never echo raw config or tokens.
        print(str(error) if isinstance(error, ConfigError) else f"Firebase operation failed ({type(error).__name__}); existing configuration was not validated", file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
